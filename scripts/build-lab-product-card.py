HEADER = """/*
 * KONBINI workbench — ticket 04. Generated by scripts/build-lab-product-card.py.
 * Do not edit by hand: change the script and run it again.
 *
 * Currently reviewing: the product card (ticket 11). Five rows of two real
 * product cards on the mobile grid, each row one test. Assign this template
 * to a page with the handle "lab". Card titles carry placeholder translations
 * for the workbench language switch.
 */
"""


def card(handle):
    return {
        "type": "product-card",
        "settings": {"product": handle, "product_card_gap": 0, "width": "fill", "width_mobile": "fill"},
        "blocks": {
            "gallery": {
                "type": "_product-card-gallery",
                "settings": {"image_ratio": "square", "border": "none", "border_radius": 0},
            },
            "title": {
                "type": "product-title",
                "settings": {"type_preset": "paragraph", "padding-block-start": 0},
            },
            "price": {
                "type": "price",
                "settings": {"show_sale_price_first": True, "type_preset": "h6"},
            },
        },
        "block_order": ["gallery", "title", "price"],
    }


def build():
    missing = [handle for handle, _note in PRODUCTS if handle not in TRANSLATIONS]
    if missing:
        raise SystemExit("no translations for: " + ", ".join(missing))
    blocks = {"card_%02d" % (i + 1): card(handle) for i, (handle, _note) in enumerate(PRODUCTS)}
    template = {
        "sections": {
            "bench": {
                "type": "lab-bench",
                "blocks": blocks,
                "block_order": list(blocks),
                "settings": {
                    "layout": "grid",
                    "stage_background": "#ffffff",
                    "show_specimen": False,
                    "translations": json.dumps(TRANSLATIONS, ensure_ascii=False),
                    "padding-block-start": 24,
                    "padding-block-end": 24,
                },
            }
        },
        "order": ["bench"],
    }
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "templates", "page.lab.json")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(HEADER)
        json.dump(template, handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    print("wrote", path, "with", len(blocks), "cards")


if __name__ == "__main__":
    build()
