#!/usr/bin/env python3
"""Builds templates/page.lab.json: the workbench set-up for the product card.

Run from the repo root:  python3 scripts/build-lab-product-card.py

The template is generated so the rows stay deliberate. Each row of two cards
is one test from ticket 11. Change PRODUCTS here, not the JSON.
"""
import json
import os

# (handle, what the card is there to show)
PRODUCTS = [
    # Row 1: one long title next to a short one. The row-alignment rule.
    ("yamachu-gochujang-korean-chili-paste-pikantna-pasta-z-chili-40-g", "66 characters, size last"),
    ("morinaga-mori-nu-tofu-jedwabiste-miekkie-305-g", "medium title"),
    # Row 2: two long titles. Both keep their lines; nothing is cut for alignment.
    ("yamachu-doubanjiang-chinese-chili-paste-ostra-pasta-z-fermentowanego-bobu-i-chili-40-g", "long"),
    ("marutomo-dashinomoto-shin-katsuo-bonito-soup-stock-dashi-no-moto-bulion-rybny-katsuo-dashi-8-x-6g-48-g",
     "over the clamp, size in brackets"),
    # Row 3: the Pocari case. Titles that differ only in the size.
    ("pocari-sweat-ion-supply-drink-japonski-napoj-izotoniczny-74-g-1-l", "in stock"),
    ("pocari-sweat-ion-supply-drink-japonski-napoj-izotoniczny-300-ml", "sold out"),
    # Row 4: a sale price, and a size that is not at the end of the title.
    ("ottogi-instant-noodles-jin-ramen-mild-120-g-zupa-jin-ramen-lagodna", "on sale, size mid-title"),
    ("lotte-paluszki-pepero-z-nadzieniem-czekoladowym-45-g", "on sale"),
    # Row 5: no photograph, and a title with no size at all.
    ("2-pair-wooden-chopsticks-white-grey-with-ceramic-rests-aito", "no image, no size"),
    ("cjw-misung-koreanski-mirin-410-ml", "three slashes"),
]

HEADER = """/*
 * KONBINI workbench — ticket 04. Generated by scripts/build-lab-product-card.py.
 * Do not edit by hand: change the script and run it again.
 *
 * Currently reviewing: the product card (ticket 11). Five rows of two real
 * product cards on the mobile grid, each row one test. Assign this template
 * to a page with the handle "lab".
 */
"""


def card(handle):
    return {
        "type": "product-card",
        "settings": {"product": handle, "product_card_gap": 0, "width": "fill", "width_mobile": "fill"},
        "blocks": {
            "gallery": {
                "type": "_product-card-gallery",
                "settings": {"image_ratio": "square", "border": "none", "border_radius": 0},
            },
            "title": {
                "type": "product-title",
                "settings": {"type_preset": "paragraph", "padding-block-start": 0},
            },
            "price": {
                "type": "price",
                "settings": {"show_sale_price_first": True, "type_preset": "h6"},
            },
        },
        "block_order": ["gallery", "title", "price"],
    }


def build():
    blocks = {"card_%02d" % (i + 1): card(handle) for i, (handle, _note) in enumerate(PRODUCTS)}
    template = {
        "sections": {
            "bench": {
                "type": "lab-bench",
                "blocks": blocks,
                "block_order": list(blocks),
                "settings": {
                    "layout": "grid",
                    "stage_background": "#ffffff",
                    "show_specimen": False,
                    "padding-block-start": 24,
                    "padding-block-end": 24,
                },
            }
        },
        "order": ["bench"],
    }
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "templates", "page.lab.json")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(HEADER)
        json.dump(template, handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    print("wrote", path, "with", len(blocks), "cards")


if __name__ == "__main__":
    build()
